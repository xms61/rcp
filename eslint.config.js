import { builtinModules } from 'node:module';
import js from '@eslint/js';
import pluginRouter from '@tanstack/eslint-plugin-router';
import vitest from '@vitest/eslint-plugin';
import { defineConfig, globalIgnores } from 'eslint/config';
import reactHooks from 'eslint-plugin-react-hooks';
import tseslint from 'typescript-eslint';

// What src/domain/ may not import: UI and framework packages, Node built-ins with or without `node:`, and the
// other src/ layers (ARCHITECTURE.md). Tested in scripts/lint-rules.test.mjs.
const nodeBuiltins = builtinModules.filter((name) => !name.startsWith('node:')).join('|');
const OUTSIDE_DOMAIN = [
  '^(react|react-dom)(/|$)',
  '^@tanstack/',
  '^node:',
  `^(${nodeBuiltins})(/|$)`,
  '^(\\.\\./)+(routes|router|routeTree\\.gen|server|db)(/|$)',
].join('|');

export default defineConfig(
  // scripts/ is plain Node tooling with its own tests; routeTree.gen.ts is generated by TanStack Router.
  globalIgnores(['dist/', 'scripts/', 'src/routeTree.gen.ts']),
  js.configs.recommended,
  tseslint.configs.strictTypeChecked,
  {
    languageOptions: {
      parserOptions: { projectService: true, tsconfigRootDir: import.meta.dirname },
    },
  },
  // JavaScript config files sit outside the TypeScript project, so the type-aware rules skip them.
  { files: ['**/*.js'], extends: [tseslint.configs.disableTypeChecked] },
  reactHooks.configs.flat.recommended,
  pluginRouter.configs['flat/recommended'],
  {
    files: ['src/**/*.test.{ts,tsx}'],
    ...vitest.configs.recommended,
    rules: {
      ...vitest.configs.recommended.rules,
      // A skipped or focused test turns a failing check green without fixing anything.
      'vitest/no-disabled-tests': 'error',
      'vitest/no-focused-tests': 'error',
    },
  },
  {
    // The dependency direction in ARCHITECTURE.md: the domain layer is plain TypeScript.
    files: ['src/domain/**'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              regex: OUTSIDE_DOMAIN,
              message:
                'src/domain/ is plain TypeScript: no React, TanStack, Node APIs or other src/ layers. Do the I/O in the route or server function and pass plain values into the domain function.',
            },
          ],
        },
      ],
    },
  },
);
